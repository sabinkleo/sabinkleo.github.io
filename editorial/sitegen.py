def esc(value):
    return escape(str(value), quote=True)


def safe_json(obj):
    # Keep a title containing HTML or a closing script tag inside the JSON string.
    return json.dumps(obj, ensure_ascii=False).replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")


def day(value):
    if "T" in value:
        return datetime.fromisoformat(value.replace("Z", "+00:00")).astimezone(ZONE).date()
    return date.fromisoformat(value)


def display_date(value):
    d = day(value)
    return f"{d.day:02d} {MONTHS[d.month-1]} {d.year}"


def time(value):
    return f'<time datetime="{esc(value)}">{display_date(value)}</time>'


def confidence(record):
    return {"high": "Alta", "moderate": "Moderada"}[record["evidence_level"]]


def chapter(record):
    return EVENTS[record["event_type"]]


def canonical(record):
    return BASE + record["slug"] + "/"


